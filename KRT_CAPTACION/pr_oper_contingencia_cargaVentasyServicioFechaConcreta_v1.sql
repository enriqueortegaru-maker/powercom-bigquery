BEGIN


  --LOCAL
  DECLARE VFECHA_REGISTRO_ORIGEN_DT DATE; DECLARE VFECHA_REGISTRO_DESTINO_DT DATE; 
  --FIN LOCAL
  --DECLARE VMARCA STRING;DECLARE VFECHA_REGISTRO_ORIGEN_ID, VFECHA_REGISTRO_DESTINO_ID INT64;  SET VMARCA="R";  SET VFECHA_REGISTRO_ORIGEN_ID=20251002;SET VFECHA_REGISTRO_DESTINO_ID=20251003;  
  --LOCAL
  SET VFECHA_REGISTRO_ORIGEN_DT=PARSE_DATE('%Y%m%d', CAST(VFECHA_REGISTRO_ORIGEN_ID AS STRING));
  SET VFECHA_REGISTRO_DESTINO_DT=PARSE_DATE('%Y%m%d', CAST(VFECHA_REGISTRO_DESTINO_ID AS STRING));



  -----  VUELCO   REGISTROS DE VENTAS Y SERVICIOS DE DIA DESTINO EN TABLA TEMPORAL
  -----  RECUPERO REGISTROS DE VENTAS Y SERVICIOS DE DIA ORIGEN PARA MARCA 
  -----  ELIMINO  REGISTROS DE VENTAS Y SERVICIOS DE DIA DESTINO
  -----  RECUPERO REGISTROS DE VENTAS Y SERVICIOS DE DIA ORIGEN PARA MARCA 

  
  CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_CAPTACION.CONTINGENCIA_VENTAS_CAPTACION_DIA_DESTINO` 
  OPTIONS(expiration_timestamp = TIMESTAMP_ADD(CURRENT_TIMESTAMP(), INTERVAL 7 DAY)) AS
  SELECT *
  FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_VENTAS_CAPTACION`
  WHERE fecha_calc_dt=VFECHA_REGISTRO_DESTINO_DT;

  CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_CAPTACION.CONTINGENCIA_SERVICIOS_CAPTACION_DIA_DESTINO` 
  OPTIONS(expiration_timestamp = TIMESTAMP_ADD(CURRENT_TIMESTAMP(), INTERVAL 7 DAY)) AS
  SELECT *
  FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_SERVICIOS_CAPTACION`
  WHERE fecha_calc_dt=VFECHA_REGISTRO_DESTINO_DT;


  CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_CAPTACION.CONTINGENCIA_VENTAS_CAPTACION_DIA_ORIGEN` 
  OPTIONS(expiration_timestamp = TIMESTAMP_ADD(CURRENT_TIMESTAMP(), INTERVAL 7 DAY)) AS
  SELECT *
  FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_VENTAS_CAPTACION`
  WHERE fecha_calc_dt=VFECHA_REGISTRO_ORIGEN_DT;

  CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_CAPTACION.CONTINGENCIA_SERVICIOS_CAPTACION_DIA_ORIGEN` 
  OPTIONS(expiration_timestamp = TIMESTAMP_ADD(CURRENT_TIMESTAMP(), INTERVAL 7 DAY)) AS
  SELECT *
  FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_SERVICIOS_CAPTACION`
  WHERE fecha_calc_dt=VFECHA_REGISTRO_ORIGEN_DT;


  DELETE FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_VENTAS_CAPTACION` WHERE fecha_calc_dt=VFECHA_REGISTRO_DESTINO_DT and marca_ds=VMARCA;

  INSERT INTO  `mm-commissions-reporting.KRT_CAPTACION.AGG_VENTAS_CAPTACION` 
  SELECT VFECHA_REGISTRO_DESTINO_DT,
  * except(fecha_calc_dt)
  FROM (
    SELECT *
    FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_VENTAS_CAPTACION`
    WHERE fecha_calc_dt=VFECHA_REGISTRO_ORIGEN_DT and marca_ds=VMARCA
  );


  DELETE FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_SERVICIOS_CAPTACION` WHERE fecha_calc_dt=VFECHA_REGISTRO_DESTINO_DT and marca_ds=VMARCA;

  INSERT INTO  `mm-commissions-reporting.KRT_CAPTACION.AGG_SERVICIOS_CAPTACION` 
  SELECT VFECHA_REGISTRO_DESTINO_DT,
  * except(fecha_calc_dt)
  FROM (
    SELECT *
    FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_SERVICIOS_CAPTACION`
    WHERE fecha_calc_dt=VFECHA_REGISTRO_ORIGEN_DT and marca_ds=VMARCA
  );


  ---- DECOMISIONES

  CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_CAPTACION.CONTINGENCIA_DECOMISIONES_DIA_DESTINO` 
  OPTIONS(expiration_timestamp = TIMESTAMP_ADD(CURRENT_TIMESTAMP(), INTERVAL 7 DAY)) AS
  SELECT *
  FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_DECOMISIONES`
  WHERE fecha_calc_dt=VFECHA_REGISTRO_DESTINO_DT;


  DELETE FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_DECOMISIONES` WHERE fecha_calc_dt=VFECHA_REGISTRO_DESTINO_DT and marca_ds=VMARCA;

  INSERT INTO  `mm-commissions-reporting.KRT_CAPTACION.AGG_DECOMISIONES` 
  SELECT VFECHA_REGISTRO_DESTINO_DT,
  * except(fecha_calc_dt)
  FROM (
    SELECT *
    FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_DECOMISIONES`
    WHERE fecha_calc_dt=VFECHA_REGISTRO_ORIGEN_DT and marca_ds=VMARCA
  );



  ---- RAPPEL VENTAS

  CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_CAPTACION.CONTINGENCIA_RAPPEL_VENTAS_CAPTACION_DIA_DESTINO` 
  OPTIONS(expiration_timestamp = TIMESTAMP_ADD(CURRENT_TIMESTAMP(), INTERVAL 7 DAY)) AS
  SELECT *
  FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_RAPPEL_VENTAS`
  WHERE fecha_calc_dt=VFECHA_REGISTRO_DESTINO_DT;


  DELETE FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_RAPPEL_VENTAS` WHERE fecha_calc_dt=VFECHA_REGISTRO_DESTINO_DT and marca_ds=VMARCA;

  INSERT INTO  `mm-commissions-reporting.KRT_CAPTACION.AGG_RAPPEL_VENTAS` 
  SELECT VFECHA_REGISTRO_DESTINO_DT,
  * except(fecha_calc_dt)
  FROM (
    SELECT *
    FROM `mm-commissions-reporting.KRT_CAPTACION.AGG_RAPPEL_VENTAS`
    WHERE fecha_calc_dt=VFECHA_REGISTRO_ORIGEN_DT and marca_ds=VMARCA
  );




END