BEGIN
 
  CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_CAPTACION.AJUSTES_PORTABILIDADES_INTRAGRUPO` AS
  SELECT C.*, F.OPERADOR_DONANTE_ID OPERADOR_FIJO_ID, F.OPERADOR_DONANTE_DS OPERADOR_DONANTE_FIJO, M.operador_donante_id OPERADOR_MOVIL_ID, M.operador_donante_ds OPERADOR_DONANTE_MOVIL
  FROM `mm-commissions-reporting.KRT_CAPTACION.MARCO_RETRIBUTIVOxCANAL` C
  LEFT JOIN   `dw-cloud-euskaltel-prod-283409.D50_EDW.edw_120_portabilidad_fijo` F ON C.servicio_id = F.servicio_receptor_id
  LEFT JOIN  `dw-cloud-euskaltel-prod-283409.D50_EDW.edw_130_portabilidad_movil` M ON C.servicio_id = M.servicio_receptor_id;
  
  UPDATE `mm-commissions-reporting.KRT_CAPTACION.AJUSTES_PORTABILIDADES_INTRAGRUPO` SET OPERADOR_FIJO_ID=CAST(NULL AS STRING) WHERE CONTAINS_SUBSTR(OPERADOR_FIJO_ID,"DESCONOCIDO"); 
  UPDATE `mm-commissions-reporting.KRT_CAPTACION.AJUSTES_PORTABILIDADES_INTRAGRUPO` SET OPERADOR_MOVIL_ID=CAST(NULL AS STRING) WHERE CONTAINS_SUBSTR(OPERADOR_MOVIL_ID,"DESCONOCIDO"); 

END