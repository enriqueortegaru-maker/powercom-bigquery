BEGIN

	DECLARE vMES_COMISION_ID, VVERSION_PROD INT64;

	DECLARE vMES_COMISION_DT, VMES_DT DATE;
--  VARIABLES LOCALES	
--  DECLARE vMES_COMISION_ID, DESDE,HASTA, VERSION_FL INT64; SET DESDE=20230401;SET HASTA=20230430;SET VERSION_FL=7;
	SET	vMES_COMISION_ID= CAST(FORMAT_DATE("%Y%m",DATE_TRUNC(PARSE_DATE('%Y%m%d', CAST (VDESDE AS string)),month)) AS INT64); 
	SET vMES_COMISION_DT=DATE_TRUNC(PARSE_DATE('%Y%m%d', CAST (VDESDE AS string)),month);
  SET VMES_DT=(SELECT DATE_TRUNC(PARSE_DATE('%Y%m%d', CAST (VDESDE AS string)),month));
  SET VVERSION_PROD=(SELECT `mm-commissions-reporting.KRT_CAPTACION.f_obtenerVersionDeFlujoVigenteEnMes`(VMES_DT));

	--- ACTUALIZAMOS EL HISTORICO DE CARTERA UNICAMENTE SI LA VERSION DE FLUJO EJECUTADA COINCIDE CON LA VERSION DEL FLUJO EN PRODUCCION
	if VVERSION_PROD=VVERSION_FL THEN 

			--- PASO 1: CREO TABLAS HISTORICO_COMISIONES_CARTERA_FACTURADO_EN_PROCESO Y HISTORICO_DECOMISIONES_CARTERA_FACTURADO_EN_PROCESO
				
			CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_CAPTACION.CAPTACION_HISTORICO_EN_PROCESO` AS 
		--	SELECT * FROM `mm-commissions-reporting.KRT_CARTERA.f_vt_comisiones_en_proceso`(vdesde, vhasta);
			SELECT * FROM `mm-commissions-reporting.KRT_CAPTACION.f_vt_comisiones_captacion_historico_en_proceso`(vdesde, vhasta);

			--- PASO 2: ACTUALIZO TABLAS HISTORICO_COMISIONES_CARTERA_FACTURADO y HISTORICO_DECOMISIONES_CARTERA_FACTURADO
			--DELETE FROM `mm-commissions-reporting.KRT_CARTERA.HISTORICO_COMISIONES_CARTERA_FACTURADO` where mes_comision_dt=vmes_comision_dt and version=vversion;
			DELETE FROM `mm-commissions-reporting.KRT_CAPTACION.ACC_CAPTACION_HISTORICO` where desde=VDESDE; 
				
			INSERT INTO `mm-commissions-reporting.KRT_CAPTACION.ACC_CAPTACION_HISTORICO`  
			SELECT * FROM `mm-commissions-reporting.KRT_CAPTACION.CAPTACION_HISTORICO_EN_PROCESO`;



		--- PASO 2.0 ACTUALIZO ACC_CLAWBACK_HISTORICO 

			--- CLAWBACK
			DELETE FROM `mm-commissions-reporting.KRT_CAPTACION.ACC_CLAWBACK_HISTORICO` AS h 	WHERE	h.mes_decomision_id=vMES_COMISION_ID and h.VERSION=VVERSION_FL;

			INSERT INTO	`mm-commissions-reporting.KRT_CAPTACION.ACC_CLAWBACK_HISTORICO`
			SELECT DISTINCT * , vversion_fl	FROM `mm-commissions-reporting.KRT_CAPTACION.CLAWBACK`;


		--- PASO 2.1 ACTUALIZO ACC_CLAWBACK_24M_HISTORICO 

				--- CLAWBACK
			DELETE FROM `mm-commissions-reporting.KRT_CAPTACION.ACC_CLAWBACK_24M_HISTORICO` AS h 	WHERE	h.mes_decomision_id=vMES_COMISION_ID and h.VERSION=VVERSION_FL;

			INSERT INTO	`mm-commissions-reporting.KRT_CAPTACION.ACC_CLAWBACK_24M_HISTORICO`
			SELECT DISTINCT * , vversion_fl	FROM `mm-commissions-reporting.KRT_CAPTACION.CLAWBACK_24M`;


		--- PASO 5.0:ACTUALIZO HISTORICO DE COMISIONES DUPLICADAS EN MESES PREVIOS
			DELETE FROM  `mm-commissions-reporting.KRT_CAPTACION.COMISIONES_PUBLICADAS_MESES_PREVIOS_HISTORICO`
			WHERE mes_comision_id=vMES_COMISION_ID;

			INSERT  INTO `mm-commissions-reporting.KRT_CAPTACION.COMISIONES_PUBLICADAS_MESES_PREVIOS_HISTORICO`
			SELECT * FROM  `mm-commissions-reporting.KRT_CAPTACION.LOG_0801_COMISIONES_PUBLICADAS_MESES_PREVIOS`;



	--- PASO 6.0: ACTUALIZO HISTORICO DE COMISIONES DUPLICADAS EN MES DE COMISION
			--CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_CAPTACION.COMISIONES_DUPLICADAS_MES_COMISION_HISTORICO` AS
			--SELECT * FROM  `mm-commissions-reporting.KRT_CAPTACION.LOG_0801_COMISIONES_DUPLICADAS_MES_COMISION`;

			DELETE FROM  `mm-commissions-reporting.KRT_CAPTACION.COMISIONES_DUPLICADAS_MES_COMISION_HISTORICO`
			WHERE mes_comision_id=vMES_COMISION_ID;

			INSERT  INTO `mm-commissions-reporting.KRT_CAPTACION.COMISIONES_DUPLICADAS_MES_COMISION_HISTORICO`
			SELECT * FROM  `mm-commissions-reporting.KRT_CAPTACION.LOG_0801_COMISIONES_DUPLICADAS_MES_COMISION`;

		END IF;

END