BEGIN
  DECLARE VFECHA_CALC_DT DATE;
  DECLARE VFECHA_CALC_ID INT64;  
  DECLARE VMES_ID,  VFECHA_PUBLICACION INT64;
  DECLARE VPUBLICADO BOOL;
  --DECLARE VMARCA_DS STRING DEFAULT "EUSKALTEL"; DECLARE VDESDE INT64;SET VDESDE=20251001; 
  SET VMES_ID=CAST( SAFE_DIVIDE(VDESDE,100) AS INT64);

  --SELECT VFECHA_CALC_DT, VFECHA_CALC_ID, VMES_ID;

  IF contains_substr(vmarca_ds,"EUSKALTEL") THEN 

      SET VFECHA_PUBLICACION=COALESCE((SELECT FECHA_ID FROM `mm-commissions-reporting.KRT_CARTERA.PARAM_PUBLICACION` where mes_comision_id=VMES_ID and marca_ds=vmarca_ds) ,0);
      SET VPUBLICADO= CASE WHEN VFECHA_PUBLICACION >0 THEN TRUE ELSE FALSE END;
      ---DATE_TRUNC(CURRENT_DATE(),MONTH)=DATE_TRUNC(PARSE_DATE('%Y%m%d', CAST(vdesde AS STRING)),MONTH)
      IF vPUBLICADO THEN     
         SET VFECHA_CALC_ID=VFECHA_PUBLICACION;
      ELSE
        SET VFECHA_CALC_DT=(SELECT MAX(FECHA_CALC_DT) FROM `mm-commissions-reporting.KRT_CARTERA.AGG_COMISIONES` where desde=vdesde); 
        SET VFECHA_CALC_ID=CAST(CAST(FORMAT_DATE("%Y%m%d",  VFECHA_CALC_DT) AS STRING) AS INT64);
      END IF;

      CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_CARTERA.AUDIT_CANALIZACION_EQUIPO_FIDELIZACION` AS 
      SELECT * FROM `mm-commissions-reporting.KRT_CARTERA.f_vt_canalizacion_audit_funcion_agente_equipo_fidelizacion`(vmarca_ds, vfecha_calc_id, vdesde);

  END IF;

END