BEGIN

		-- 7.3.1 CREACION DE TABLA TEMPORAL DE CARGA PARAM_SAP_ZDESCSUBAGRUPACION_LOAD
		CREATE OR REPLACE TABLE `mm-commissions-reporting.KRT_SAP.PARAM_SAP_ZDESCSUBAGRUPACION_LOAD` 
		OPTIONS(expiration_timestamp = TIMESTAMP_ADD(CURRENT_TIMESTAMP(), INTERVAL 1 DAY)) as 
		select * from `mm-commissions-reporting.KRT_SAP.f_vt_param_sap_crea_tabla_PARAM_SAP_ZDESCSUBAGRUPACION`();		



		-- 7.3.2 PROCESO REGISTROS PARAMETRIZACIONES EN TABLAS AGG  
		
		DELETE FROM `mm-commissions-reporting.KRT_SAP.AGG_PARAM_SAP_ZDESCSUBAGRUPACION`  WHERE fecha_reg_dt=CURRENT_DATE();	
		
		INSERT INTO `mm-commissions-reporting.KRT_SAP.AGG_PARAM_SAP_ZDESCSUBAGRUPACION` 
		select current_date() as fecha_reg_dt,* 
		from `mm-commissions-reporting.KRT_SAP.PARAM_SAP_ZDESCSUBAGRUPACION_LOAD`;

		-- 7.3.3 PROCESO REGISTROS DE PARAMETRIZACIONES 

		DELETE FROM `mm-commissions-reporting.KRT_SAP.PARAM_SAP_ZDESCSUBAGRUPACION`  WHERE TRUE;	


		-- 7.3.3 IMPORTO REGISTROS DE TABLAS GS 
		INSERT INTO `mm-commissions-reporting.KRT_SAP.PARAM_SAP_ZDESCSUBAGRUPACION`
		select * from `mm-commissions-reporting.KRT_SAP.PARAM_SAP_ZDESCSUBAGRUPACION_LOAD`  where ZSUBAGRUPACION is not null;



END