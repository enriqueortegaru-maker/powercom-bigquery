BEGIN

--CALL `mm-commissions-reporting.ORANGE.pr_billing_jazztel`()

  --AGREGAMOS A NIVEL DE FACTURA, SIN ID_SERVICIO
  CREATE OR REPLACE TABLE `mm-commissions-reporting.TEMP.billing_jazztel_agregado_factura`
      OPTIONS(expiration_timestamp = TIMESTAMP_ADD(CURRENT_TIMESTAMP(), INTERVAL 2 DAY)) AS

    SELECT * EXCEPT(IMPUESTO_APLICAR), (IMPORTE_SIN_IMPUESTO * IMPUESTO_APLICAR) AS IMPORT_CON_IMP_CALCULADO
    FROM (
      SELECT MARCA, ID_FACTURA, NUMERACION_FACTURA, FC_INICIO_FACT, FC_FIN_FACT, ID_CICLO, TAX
        , CASE  WHEN TAX = 21 THEN 1.21
                WHEN TAX = 7  THEN 1.07
                WHEN TAX = 8  THEN 1.08
                ELSE 1 END AS IMPUESTO_APLICAR
        , SUM(IMPORTE_SIN_IMPUESTO) AS IMPORTE_SIN_IMPUESTO, SUM(IMPORTE_CON_IMPUESTO) AS IMPORTE_CON_IMPUESTO
      FROM `mm-datamart-kd.00_SANDBOX_DWH_ORANGE.osp_billing_jazztel_202*` a
      WHERE a.id_cliente = 52993394
      GROUP BY ALL
    )
    ORDER BY FC_INICIO_FACT, ID_FACTURA;


  --AGREGAMOS A NIVEL ID_SERVICIO
  CREATE OR REPLACE TABLE `mm-commissions-reporting.TEMP.billing_jazztel_id_servicio_factura`
      OPTIONS(expiration_timestamp = TIMESTAMP_ADD(CURRENT_TIMESTAMP(), INTERVAL 2 DAY)) AS

    SELECT * EXCEPT(IMPUESTO_APLICAR), (IMPORTE_SIN_IMPUESTO * IMPUESTO_APLICAR) AS IMPORT_CON_IMP_CALCULADO
    FROM (
      SELECT MARCA, ID_FACTURA, NUMERACION_FACTURA, FC_INICIO_FACT, FC_FIN_FACT, ID_SERVICIO, SERVICE_KEY, NUM_TLF AS phone_nm, ID_CICLO, TAX
        , CASE  WHEN TAX = 21 THEN 1.21
                WHEN TAX = 7  THEN 1.07
                WHEN TAX = 8  THEN 1.08
                ELSE 1 END AS IMPUESTO_APLICAR
        , SUM(IMPORTE_SIN_IMPUESTO) AS IMPORTE_SIN_IMPUESTO, SUM(IMPORTE_CON_IMPUESTO) AS IMPORTE_CON_IMPUESTO
      FROM `mm-datamart-kd.00_SANDBOX_DWH_ORANGE.osp_billing_jazztel_202*` a
      WHERE a.id_cliente = 52993394
      GROUP BY ALL
    )
    ORDER BY FC_INICIO_FACT, ID_FACTURA, ID_SERVICIO;



  --AGREGAMOS A NIVEL ID_SERVICIO
  CREATE OR REPLACE TABLE `mm-commissions-reporting.TEMP.billing_jazztel_servicio_en_cada_factura`
      OPTIONS(expiration_timestamp = TIMESTAMP_ADD(CURRENT_TIMESTAMP(), INTERVAL 2 DAY)) AS
      
      SELECT ID_FACTURA, NUMERACION_FACTURA, ID_SERVICIO, SERVICE_KEY, NUM_TLF AS phone_nm
      FROM `mm-datamart-kd.00_SANDBOX_DWH_ORANGE.osp_billing_jazztel_202*` a
      WHERE a.id_cliente = 52993394
      GROUP BY ALL
      ORDER BY 1,2,3,4;

END